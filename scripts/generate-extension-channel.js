const fs = require('fs');
const path = require('path');

const VALID_CHANNELS = new Set(['stable', 'prerelease']);
const outputPath = path.resolve(__dirname, '..', 'src', 'generated', 'extensionChannel.ts');
const packageJsonPath = path.resolve(__dirname, '..', 'package.json');

function getArgValue(flagName) {
    const index = process.argv.indexOf(flagName);
    if (index === -1 || index + 1 >= process.argv.length) {
        return undefined;
    }

    return process.argv[index + 1];
}

function resolveChannel() {
    const explicitChannel = getArgValue('--channel')?.trim();
    if (explicitChannel) {
        if (!VALID_CHANNELS.has(explicitChannel)) {
            throw new Error(`Invalid --channel '${explicitChannel}'. Expected stable or prerelease.`);
        }

        return explicitChannel;
    }

    try {
        const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
        return packageJson.preview === false ? 'stable' : 'prerelease';
    } catch {
        return 'prerelease';
    }
}

function main() {
    const channel = resolveChannel();
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(
        outputPath,
        `// This file is generated by scripts/generate-extension-channel.js.\nexport const GENERATED_EXTENSION_CHANNEL = '${channel}' as const;\n`,
        'utf8'
    );
    console.log(`[GLuaLS] Generated extension channel artifact: ${channel}`);
}

main();
